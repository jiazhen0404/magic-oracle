<p>吵完架的那個晚上，兩個人在同一個空間卻不說話。你想和好，但又覺得不是自己的錯；對方傳來一句「好啦對不起」，你卻更生氣了。隔天一切看起來恢復正常，可是你心裡知道，那件事其實沒有被處理。</p>

