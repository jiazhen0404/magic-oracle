/**
 * @param dbgA  result.debug.A
 * @param dbgB  result.debug.B
 * @param zlKey result.dimensions.zhongliang.key（實際的力道方向）
 */
function palace(dbgA, dbgB, zlKey) {
  const a = palaceType(dbgA.dayGan, dbgA.dayZhi);
  const b = palaceType(dbgB.dayGan, dbgB.dayZhi);
  const aligned = PAL_MATCH[zlKey] === a;
  return {
    aKey: a, bKey: b, aligned,
    body: PAL_SELF[a] + PAL_OTHER[b] + PAL_CLASH[a][b]
        + (aligned ? '' : PAL_BRIDGE[a])
  };
}

