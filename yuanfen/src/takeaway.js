/* 段落 title → 取哪一組、用哪個 key */
function takeaway(section, ctx) {
  const { band, weak, strong, zl, wendu, changdu, midu, tempo, place } = ctx;
  const map = {
    '你們的緣分，究竟有多深？':                 () => T.table,
    '你們是怎麼開始的？':                       () => T.tempo[ctx.tempo],
    '你們是在什麼樣的場合遇上的？':             () => T.place[ctx.place],
    '你們現在，到底算是什麼？':       () => T.now[band],
    '明明有感覺，為什麼就是差那一步？':           () => T.weak[weak],
    '你們之間，最值得珍惜的是什麼？':           () => T.strong[strong],
    '他習慣用什麼方式靠近一個人？':     () => T.position[zl],
    '你喜歡的他，和真實的他一樣嗎？':           () => T.appearance[wendu],
    '如果真的在一起，他看重的會是什麼？':         () => T.attitude[changdu],
    '那你呢？你真正需要的是什麼樣的愛？':       () => T.self[zl],
    '在他面前，你為什麼會變得不像自己？':       () => T.blind[zl],
    '你們想要的愛情，真的是同一種嗎？':         () => T.values[changdu],
    '為什麼同一件事，你們總是想得不一樣？':     () => T.reading[wendu],
    '只有你們兩個人的時候，是什麼樣子？': () => T.midu[midu],
    '近期，你們之間可能先出現什麼變化？':       () => T.near[band],
    '再往後，你們有機會走到哪裡？':             () => T.later[band],
    '他有在往前嗎？從哪裡看得出來？': () => T.watch[zl],
    '什麼事，最容易讓你們就這樣停住？':           () => T.caution[weak],
    '如果你想往前一步，現在可以怎麼做？':         () => T.advice[zl],
    '現在最不適合做的，是哪件事？':             () => T.dont[zl],
    '關於這段緣分，你最該記住的一件事。':       () => T.keep[band]
  };
  const fn = map[section];
  return fn ? (fn() || '') : '';
}

