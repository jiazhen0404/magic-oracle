/**
 * @param key   WRAP 的段落代號
 * @param body  該段落原本的判斷句
 * @param seed  render 用的種子
 * @param salt  避免各段抽到同一組
 */
function wrap(key, body, seed, salt) {
  const w = WRAP[key];
  if (!w || !body) return body;
  const pick = (arr, s) => {
    const h = (seed ^ Math.imul(s, 2654435761)) >>> 0;
    return arr[h % arr.length];
  };
  return pick(w.open, salt * 7) + body + pick(w.close, salt * 13);
}

module.exports = { wrap, WRAP };
