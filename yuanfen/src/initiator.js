/**
 * @param d  result.dimensions
 */
function initiator(d) {
  const w = WHO[d.zhongliang.key] || WHO.bihe;
  const k = INI_SWEET.includes(d.wendu.key) ? 'sweet'
          : INI_HARSH.includes(d.wendu.key) ? 'harsh' : 'plain';
  return { label: w.label, body: w.body + HOW[k], how: k };
}

