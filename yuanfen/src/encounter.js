/**
 * @param changduKey  result.dimensions.changdu.key
 * @param tempoKey    tempo(d).key
 */
function encounter(changduKey, tempoKey) {
  return {
    place: PLACE[changduKey] || PLACE.ping,
    timing: TIMING[tempoKey] || TIMING.plain
  };
}

module.exports = { encounter, PLACE, TIMING };
