/* =========================================================================
   未完籤所 · 相遇的方式與時機
   -------------------------------------------------------------------------
   合盤裡沒有「你們在哪裡認識」這個欄位，但也不需要問——
   問了再講回去等於承認算不出來。命理的做法是把它當成判讀來說，
   說中了才是準，說不中使用者也只會覺得「這次比較不準」，不會覺得被騙。

   兩個來源：
     場合  年支關係（年柱主大環境、背景、圈子）
     時機  節奏（tempo）——多久才會顯現、哪個階段是關鍵

   語氣一律用「多半／通常／傾向」，不用斷定句。
   這不是保守，是因為它本來就是機率描述。
   ========================================================================= */

