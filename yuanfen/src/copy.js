/* ---------- 種子與抽樣 ---------- */

function seedOf(a, b) {
  const k = [a, b].map(x => x.y * 10000 + x.m * 100 + x.d)
                  .sort((p, q) => p - q).join('-');
  let h = 2166136261;
  for (let i = 0; i < k.length; i++) { h ^= k.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

