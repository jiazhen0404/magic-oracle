function pick(arr, seed, salt) {
  if (!arr || !arr.length) return '';
  if (arr.length === 1) return arr[0];
  const h = (seed ^ Math.imul(salt, 2654435761)) >>> 0;
  return arr[h % arr.length];
}

// 同一段的 open 與 close 用不同 salt，避免兩者連動
const SCENES = ['交往', '曖昧', '分開', '未定'];

/* core 依關係情境取版；情境不參與計分，只影響措辭 */
/* core 可以是一句話，也可以是一組同義句。
   同義句必須可以互換——只要想得出一個盤面讓其中一句成立、另一句不成立，
   那就不是同義句，是兩個不同的判斷，不可以放在一起。 */
function coreOf(block, scene, seed) {
  const c = block.core;
  if (typeof c === 'string') return c;              // 尚未分版的區塊
  const v = c[scene] || c['交往'];
  if (typeof v === 'string') return v;
  let h = Math.imul((seed || 0) ^ 0x9E3779B1, 0x85EBCA6B);
  h ^= h >>> 13;
  return v[(h >>> 0) % v.length];
}

function compose(block, seed, salt, allowOpen, scene) {
  // 開場句只給最需要被點出來的那一段用；三段都加會變成公式
  const open  = allowOpen ? pick(block.open, seed, salt * 31) : '';
  const close = pick(block.close, seed, salt * 97);
  return [open, coreOf(block, scene, seed ^ Math.imul(salt, 0x27220A95)), close].filter(Boolean).join('');
}

