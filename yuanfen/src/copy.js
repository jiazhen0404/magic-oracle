/* ---------- 組裝 ---------- */

function band(total) {
  return TOTAL_BANDS.find(b => total >= b.min);
}

/**
 * @param result  yuanfen() 的輸出
 * @param birth   { a:{y,m,d}, b:{y,m,d} } —— 用來產生穩定種子
 * @param names   { A:'你', B:'對方' }
 */
function render(result, birth, names = { A: '你', B: '對方' }, scene = '交往') {
  const d = result.dimensions;
  const b = band(result.total);
  const seed = seedOf(birth.a, birth.b);
  const fill = s => s.replace(/\{A\}/g, names.A).replace(/\{B\}/g, names.B);

  // 分數最低的維度才配開場句
  const lowest = ['wendu', 'zhongliang', 'changdu']
    .sort((a, b) => d[a].score - d[b].score)[0];

  // 盤面風味：綁在命盤上，不同的盤真的會讀到不同的句子
  const fl = flavour(result.debug.A);

  let zl = fill(compose(ZHONGLIANG[d.zhongliang.key], seed, SALT.zhongliang,
                        lowest === 'zhongliang', scene));
  if (d.zhongliang.yinyang) zl += ZHONGLIANG_YINYANG[d.zhongliang.key === 'bihe' ? 'bihe' : 'other'];
  zl += fl.zhongliang;                    // 盤面風味永遠放最後

  const cd = compose(CHANGDU[d.changdu.key], seed, SALT.changdu, lowest === 'changdu', scene)
           + pick(CHANGDU_NAYIN[d.changdu.nayinKey], seed, SALT.changdu * 13)
           + fl.changdu;

  const tp = tempo(d, result.cross);
  const ini = initiator(d);
  const ch = chance(d, result.cross, tp.key, shape(d));

  return fillNames({
    total: result.total,
    label: b.label,
    title: b.title,
    tempo: tp.name,
    tempoLine: tp.intro,
    initiator: ini.label,
    chance: ch.label,
    chanceLine: ch.line,
    chanceNote: ch.note,
    headline: b.label + '·' + b.title,
    poem: pick(b.poems, seed, SALT.poem),
    summary: compose(b, seed, SALT.summary, true, scene),
    sections: [
      { name: '緣的溫度', score: d.wendu.score,
        text: compose(WENDU[d.wendu.key], seed, SALT.wendu, lowest === 'wendu', scene)
              + fl.wendu },
      { name: '緣的重量', score: d.zhongliang.score, text: zl },
      { name: '緣的長度', score: d.changdu.score, text: cd }
    ]
  }, names);
}

module.exports = {
  render, band, seedOf, pick, compose, coreOf, SCENES,
  TOTAL_BANDS, WENDU, ZHONGLIANG, CHANGDU, CHANGDU_NAYIN
};
