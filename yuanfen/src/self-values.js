/* 命名避開 copy.js 的 pick —— bundle 會把所有模組併到同一層 */
const svPick = (obj, key, names = { A: '你', B: '{B}' }) => {
  const t = obj[key];
  if (!t) return '';
  return t.replace(/\{A\}/g, names.A).replace(/\{B\}/g, names.B);
};

